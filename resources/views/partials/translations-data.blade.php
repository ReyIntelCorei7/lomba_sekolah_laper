/**
 * Get translation by key
 * @param {string} key - Translation key
 * @param {string} lang - Language code (id/en)
 * @returns {string} - Translated text
 */
window.t = function (key, lang) {
  const translation = window.translations[key];
  if (!translation) return key;
  return translation[lang] || translation['id'] || key;
};

/**
 * Auto-translate elements with data-translate attribute
 * Usage: <span data-translate="key">Default Text</span>
 */
window.applyTranslations = function (lang) {
  lang = lang || localStorage.getItem('lang') || 'id';

  // Translate elements with data-translate attribute
  document.querySelectorAll('[data-translate]').forEach(el => {
    const key = el.getAttribute('data-translate');
    if (window.translations[key]) {
      el.textContent = window.translations[key][lang];
    }
  });

  // Update HTML lang attribute
  document.documentElement.lang = lang === 'id' ? 'id' : 'en';
};

/**
 * Initialize translation system on page load
 */
document.addEventListener('DOMContentLoaded', function () {
  // Apply translations on page load
  const savedLang = localStorage.getItem('lang') || 'id';
  window.applyTranslations(savedLang);

  // Listen for language changes via custom event
  window.addEventListener('languageChanged', function (e) {
    window.applyTranslations(e.detail.lang);
  });

  // Also watch for localStorage changes (cross-tab sync)
  window.addEventListener('storage', function (e) {
    if (e.key === 'lang') {
      window.applyTranslations(e.newValue);
    }
  });
});
